#include <stdio.h>
int main() {
    int age = 12;
    float pi = 3.14;
    double root2 = 1.41421356237;
    char ch = 'a';
    printf("my age is %i\n",age);
    printf("the value of pi is %.2f\n",pi);
    printf("the value of root2 is %.3lf\n",root2);
    printf("the value of ch is %c\n",ch);
    return 0;
}